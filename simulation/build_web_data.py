#!/usr/bin/env python3
"""Bundle verified RNV1 BOM, real MuJoCo gait replay keyframes, and 12-suite
verification report into js/rnv1-data.js (window.RNV1_DATA) for the 3D CAD viewer.
"""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _flatten_floats(obj) -> list[float]:
    out: list[float] = []
    if isinstance(obj, list):
        for item in obj:
            out.extend(_flatten_floats(item))
    else:
        out.append(float(obj))
    return out


def _summarize_policy(weights_path: Path) -> dict:
    w = json.loads(weights_path.read_text(encoding="utf-8"))
    mlp_keys = ("w1", "b1", "w2", "b2", "w3", "b3")
    mlp_vals = []
    for k in mlp_keys:
        mlp_vals.extend(_flatten_floats(w[k]))
    cpg_vals = _flatten_floats(w["cpg"])
    total_params = len(mlp_vals) + len(cpg_vals)
    nonzero_mlp = sum(1 for v in mlp_vals if abs(v) > 1e-9)
    obs_dim = int(w["obs_dim"])
    h1_dim = int(w["h1_dim"])
    h2_dim = int(w["h2_dim"])
    act_dim = int(w["act_dim"])
    macs = obs_dim * h1_dim + h1_dim * h2_dim + h2_dim * act_dim
    eval_video = ROOT / "simulation" / "RNV1_walk_eval.mp4"
    return {
        "version": w.get("version", "RNV1"),
        "training_origin": "Google Colab Pro A100 — MuJoCo MJX Pure-JAX PPO (RNV1_Trained_Bundle.zip)",
        "architecture": f"{obs_dim} → {h1_dim} → {h2_dim} → {act_dim} (tanh + CPG Prior)",
        "obs_dim": obs_dim,
        "h1_dim": h1_dim,
        "h2_dim": h2_dim,
        "act_dim": act_dim,
        "control_hz": float(w["control_hz"]),
        "residual_scale": round(float(w["residual_scale"]), 4),
        "mlp_params": len(mlp_vals),
        "mlp_nonzero_params": nonzero_mlp,
        "mlp_density_pct": round(100.0 * nonzero_mlp / max(len(mlp_vals), 1), 1),
        "total_params": total_params,
        "flash_bytes": total_params * 4,
        "macs_per_step": macs,
        "cpg_freq_hz": round(cpg_vals[0], 3),
        "cpg_roll_amp_rad": round(cpg_vals[3], 3),
        "cpg_stride_amp_rad": round(cpg_vals[5], 3),
        "eval_video_path": "simulation/RNV1_walk_eval.mp4" if eval_video.exists() else None,
        "weights_header_path": "firmware/include/rnv1_policy_weights.h",
    }


def main() -> None:
    bom = json.loads((ROOT / "bom" / "rnv1_bom.json").read_text(encoding="utf-8"))
    replay = json.loads((ROOT / "simulation" / "rnv1_gait_replay.json").read_text(encoding="utf-8"))
    verification = json.loads((ROOT / "simulation" / "reports" / "verification_report.json").read_text(encoding="utf-8"))
    policy_meta = _summarize_policy(ROOT / "simulation" / "rnv1_policy_weights.json")

    payload = {
        "policy": policy_meta,
        "bom": bom,
        "replay": replay,
        "verification": verification,
    }
    out_path = ROOT / "js" / "rnv1-data.js"
    js_src = (
        "// AUTO-GENERATED BY simulation/build_web_data.py — DO NOT HAND-EDIT\n"
        "// Verified single-source-of-truth bundle: A100 Trained Policy + BOM + MuJoCo Gait Replay + 12-Suite Report\n"
        f"window.RNV1_DATA = {json.dumps(payload, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    out_path.write_text(js_src, encoding="utf-8")
    print(f"[OK] Generated {out_path} ({out_path.stat().st_size / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
